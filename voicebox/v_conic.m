            drad=(p.lecc+p.focp)*1.1;                                   % display radius
            ax=[p.cent(1)+figar*[-drad drad] p.cent(2)+[-drad drad]];   % axis limits
        end
        if doxy
            lax=lax0;                                       % matrix of bounding lines for ax=[-1 1 -1 1]
            lax(3,:)=lax(3,:).*ax;                          % bounding rectangle edges: left right bottom top. lax*[x; y; 1] is +ve for all lines if (x,y) is inside box
            lax=tz'*lax;                                    % transform bounding rectangle to canonical coordinates
            [xyax,tyax]=v_conicline(sc,lax);                % points where conic intersects bounding box lines
            liax=ceil((1:8)/2);                             % identification of line numbers
            q=~isnan(xyax(1,:)) & tyax(:)'==2;              % mask to exclude tangents and missing intersections
            xyax=[xyax(:,q) [p.smaj 0 -p.smaj 0 p.smaj; 0 -p.smin 0 p.smin 0]];     % restrict to actual crossings + ends of major/minor axes: right, top, left, bottom, right (again)
            liax=[liax(q) 5 6 6 6 7];                                               % determine matching line identification numbers
            [dum,ix]=sort((1-2*(xyax(2,:)<=0 & liax<7)).*(xyax(1,:)+2*p.smaj));     % sort intersections in order along ellipse (clockwise starting at right axis crossing)
            rinc=[8 8 64 64 0 1 1];                                                 % increment 1 for quadrant marker, 8 for left-right and 64 for top-bottom, 0 for starting point
            %
