            % however, I am not entirely sure that this is foolproof if the axis crossing lies on the rectangle itself so that the position of the crossing is also generated by v_conicline
            % the result might then depend on the ordering of these coincident points after sorting
            %
            rincs=8*all([p.smaj 0 1]*lax(:,1:2)>0) + 64*all([p.smaj 0 1]*lax(:,3:4)>0) + cumsum(rinc(liax(ix)));    % cumulative counts of: segments, left-right crossings and top-bottom crossings
            rval=find(bitand(rincs,76)==72);                % indices of segments inside the clipping rectangle (left-right and top-bottom crossing counts are both odd)
            npk=np/(ax(2)-ax(1)+ax(4)-ax(3));               % number of plotting points per unit distance (np corresponds to width+height of the clipping rectangle)
            xy1=xyax(:,ix(rval));                           % start of each valid plotting segment
            xy2=xyax(:,ix(rval+1));                         % end of each valid plotting segmentnpi
            nwc=[0 rval(2:end)==rval(1:end-1)+1];           % contiguous segment (need to exclude initial point)
            nws=~nwc;                                       % non-contiguous segment
            npi=max(ceil(npk*sum(abs(xy2-xy1),1)),nws);     % number of points in each valid plotting segment (excluding first point; must be >=1 unless contiguous)
            ix2=cumsum(npi+2*nws)-1;                        % last index for each segment
            ix1=ix2-npi+nwc;                                % first index for each segment
            xy=NaN(2,ix2(end));                             % space for the points from all valid segments
            for i=1:length(rval)                                                                                    % loop through valid segments
                ixy=ix1(i):ix2(i);                                                                                  % indices in xy(:,*) of the points belonging to this segment
                segsn=1-2*bitand(rincs(rval(i)),1);                                                                 % +1 if using x+y as dependent variable, -1 if using x-y
                sqsn=1-bitand(rincs(rval(i)),2);                                                                    % +1 y<0, -1 if y>0
                xys=xy1(1,i)+segsn*xy1(2,i)+(xy2(1,i)-xy1(1,i)+segsn*(xy2(2,i)-xy1(2,i)))/npi(i)*(nwc(i):npi(i));   % x+y or x-y values
                xys2=sc(1)*xys.^2;                                                                                 % d(1)*(x+y)^2 or d(1)*(x-y)^2
                xy(2,ixy)=(segsn*sc(1)*xys+dsg*sqsn*sqrt(sc(1)*xys2-(sc(1)+sc(5))*(xys2+sc(9))))/(sc(1)+sc(5));  % calculate y as intersection between conic and x+-y=xys
                xy(1,ixy)=xys-segsn*xy(2,ixy);                                                                      % calculate x from x+-y=xys
            end
            xy=r*xy+repmat(tz(7:8)',1,size(xy,2));          % transform conic points to user coordinates
        end
    case 6 % 6: Two intersecting lines [1 0 -1 0 0 0]
        p.nclp=[0 2 0];                                                                 % number of curves, lines and points in the conic ([0 0 -1] for whole plane)
