        p.crax=p.cent;                                                                  % one or two points where conic crosses the principal axis
        p.foci=p.cent;                                                                  % one or two foci
        p.dirx=[r1; -r1'*p.cent];                                                       % directrix line (perpendicular to principal axis)
        p.axis=[r2; -r2'*p.cent];                                                       % Principal axis
        p.line=[r; -p.cent'*r]*[sqrt(0.5+0.5*abs(ta)/g)*w12; sqrt(0.5-0.5*abs(ta)/g)*wpm];   % two lines that form the conic
        p.lecc=0;                                                                       % centre-to-focus distance (linear eccentricity)
        p.focp=0;                                                                       % focus-to-directrix distance (focal parameter)
        p.slat=0;                                                                       % semi-latus rectum
        p.smaj=0;                                                                       % semi-major axis length (focus-to-conic perpendicular to principal axis)
        p.eccy=sqrt(1-sc(1)/sc(5));                                                        % eccentricity = conic-to-focus/conic-to-directrix
