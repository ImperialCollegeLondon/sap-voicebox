                    end
                    xya=repmat(p.foci(:,1),1,2)+p.slat*p.axis(1:2)*[-1 1]; % find ends of latus recturn through p.foci(:,1)
                    v_cliplseg(xya,ax,lsp{1});
                    if size(p.foci,2)>1
                        xya=repmat(p.foci(:,2),1,2)+p.slat*p.axis(1:2)*[-1 1];
                        v_cliplseg(xya,ax,lsp{1+mod(1,length(lsp))});
                    end
                end
            case 'm'
                if ~(isempty(p.cent) || isempty(p.smin))                   % plot minor axis (p.smin)
                    if isempty(lsp)
                        lsp={'--k'};
                    end
                    xya=repmat(p.cent,1,2)+p.smin*p.axis(1:2)*[-1 1];
                    v_cliplseg(xya,ax,lsp{1});
                end
            case 'M'
                if ~(isempty(p.cent) || isempty(p.smaj))                   % plot minor axis (p.smaj)
                    if isempty(lsp)
                        lsp={'--k'};
                    end
                    xya=repmat(p.cent,1,2)+p.smaj*[-p.axis(2);p.axis(1)]*[-1 1];
                    v_cliplseg(xya,ax,lsp{1});
                end
            case 'a'
                if ~isempty(p.asym)                                         % plot asymptotes (p.asym)
                    if isempty(lsp)
                        lsp={'--k'};
                    end
                    xya=v_clipline(p.asym,ax);
                    plot(xya(1:2:3,1),xya(2:2:4,1),lsp{1});
                    if size(p.dirx,2)>1
                        plot(xya(1:2:3,2),xya(2:2:4,2),lsp{1+mod(1,length(lsp))});
                    end
                end
            case 'E' % show eccentricity (p.eccy)
                if ~isempty(p.eccy)
                    txt=[txt sprintf('e = %.3g\n',p.eccy)];
                end
            case 'A' % show semi-major axis (p.smaj)
                if ~isempty(p.smaj)
                    txt=[txt sprintf('a = %.3g\n',p.smaj)];
                end
            case 'B' % show semi-minor axis (p.smin)
                if ~isempty(p.smin)
                    txt=[txt sprintf('b = %.3g\n',p.smin)];
                end
            case 'L' % show semi-latus-rectum (p.slat)
                if ~isempty(p.slat)
                    txt=[txt sprintf('l = %.3g\n',p.slat)];
                end
            case 'F' % show linear eccentricity (p.lecc)
                if ~isempty(p.lecc)
                    txt=[txt sprintf('f = %.3g\n',p.lecc)];
                end
            case 'P' % show focal parameter (p.focp)
                if ~isempty(p.focp)
                    txt=[txt sprintf('p = %.3g\n',p.focp)];
                end
            case 'C' % conic coefficients
                if xty==12
                    txt=[txt '0=0' newline];
                else
                    txtc='';
                    coi=[1 2 5 7 8 9]; % coefficient indices into s()
                    cof=[1 2 1 2 2 1]; % coefficient scale factors
                    if s(find(s(coi)~=0,1))<0
                        cof=-cof; % make the leading coefficient positive
                    end
                    cot={'x^2','xy','y^2','x','y',''};
                    for ic=1:5
                        scoi=0+cof(ic)*s(coi(ic)); % add 0 to eliminate "-0"s
                        if scoi==1 && ic<6                          % omit +1 multiplier for ic<6
                            txtc=[txtc sprintf('+%s',cot{ic})];
                        elseif scoi==-1 && ic<6                     % omit -1 multiplier for ic<6
                            txtc=[txtc sprintf('-%s',cot{ic})];
                        elseif scoi~=0
                            txtc=[txtc sprintf('%+.2g%s',scoi,cot{ic})];
                        end
                    end
                    txt=[txt txtc((1+(txtc(1)=='+')):end) sprintf('=%.2g',0-cof(6)*s(9)) newline]; % complete the equation omitting any leading '+'
                end
        end
        hold on
    end
    %%
    if any(m=='s')
        axis(ax);           % 's' = set the axis limits
    end
    if any(m=='q')
        axis equal;         % 'q' = force axes equal
    end
    if ~isempty(txt)
        txt(end)=[];        % remove the final newline
        v_texthvc(0.05,0.95,txt,'LTk');
    end
    hold off
end
