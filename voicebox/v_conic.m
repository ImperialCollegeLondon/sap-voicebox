function [p,sc,tc,xy]=v_conic(s,m,ax,np,thr)
%V_CONIC Calculate conic parameters and/or plot conic
%
% Usage: (a) v_conic(s);                                    % plot a conic specified as a 3x3 matrix or a 1x6 vector
%        (b) v_conic([1 0 -1 0 0 -1],'cpfdakxrm0MCEABLFP'); % plot the hyperbola x^2-y^2=1 with all available information
%        (c) v_conic([1 0 4 0 0 -4],'c(r--)qs0(bx)');       % plot a dashed red ellipse x^2+4y^2=4 with its centre marked with a blue cross
%        (d) p=v_conic([1 0 -1 0 0 -1]);                    % structure p
%        lists the parameters of the hyperbola x^2-y^2=1 (see below for details)
%
%  Inputs:  s   Conic specified as either a 3x3 matrix with [x y 1]*s*[x y 1]'=0, or polynomial coefficients with s*[x^2 x*y y^2 x y 1]'=0
%           m   Option string (follow each plot option by '(...)' to give the plotting style explicitly)
%               Default options are m='' if output arguments are requested or m='c' if no output arguments given
%               'N'         Missing conic parameters are given as NaN rather than being zero-length
%               'l'         If ax input missing, use existing axis limits as plot limits rather than calculating defaults
%               'q'         Make axis scales equal
%               's'         Set the axis limits to the plotting limits
%               'c'         Plot conic [Default style: '(-k)']
%               'p'         Plot principal axis [Default style: '(:k)']
%               'x'         Indicate principal axis crossings [Default style: '(^k)']
%               '0'         Indicate conic centre [Default style: '(ok)']
%               'f'         Indicate foci [Default styles: '(+b)' and '(+r)']
%               'd'         Plot directices [Default styles: '(-b)' and '(-r)']
%               'r'         Plot latus rectums [Default styles: '(:b)' and '(:r)']
%               'm'         Plot minor axis [Default style: '(--k)']
%               'M'         Plot major axis [Default style: '(--k)']
%               'a'         Plot asymptotes [Default style: '(--k)']
%               'EABLFPC'   list values of E=eccentricity, A=semi-major ax, B=semi-minor ax, L=semi-latus-rectum, F=linear-eccentricity, P=focal-param, C=conic-coefficients
%           ax  Axis limits for plotting conic [xmin xmax ymin ymax]. Omit ax to select default limits or use 'l' option to keep existing ones.
%           np  Approximate number of points used to plot a distance equal to half the bounding box perimeter
%           thr Tolerance threshold for elements of matrix s when classifying the conic
%
% Outputs:  p       Structure containing conic parameters (points are [x;y] and lines are [a; b; c] where a*x+b*y+c=0)
%                       p.type  conic type: 4=Circle, 3=ellipse, 2=Parabola, 1=Hyperbola, 0=empty, -1=point, -2=line, -3=line-pair, -4=plane
%                       p.nclp  number of curves, lines and points in the conic ([0 0 -1] for whole plane)
%                       p.cra   xa(2,*) one or two points where conic crosses the principal axis
%                       p.cent  x0(2,1) = the centre of the conic
%                       p.foci  xf(2,*) = one or two foci
%                       p.dirx  ld(3,*) = a directrix line for each focus
%                       p.axis  la(3,1) = Principal axis
%                       p.asym  lx(3,*) = asymptote lines
%                       p.line  lc(3,*) = lines that form the conic
%                       p.lecc  f = linear eccentricity = centre-to-focus distance
%                       p.focp  p = focal parameter = focus-to-directrix distance
%                       p.slat  l = semi-latus rectum = width of conic at the focus
%                       p.smaj  a = semi-major axis length
%                       p.smin  b = semi-minor axis length
%                       p.eccy  e = eccentricity = conic-to-focus-distance/conic-to-directrix-distance
%           sc      Canonical form conic matrix with <=3 non-zero elements satisfying s=tc'*sc*tc
%           tc      Translation+Rotation transformation matrix (real coordinates to canonical coordinates)
%           xy(2,:) Rows give x and y coordinates for points forming the conic with NaN used to separate the two branches of a hyperbola
%
% Bugs:
%       1.  When drawing an ellipse, we initialize rincs with 8 if right axis-crossing is inside the rectangle horizontally PLUS 64 if it is inside vertically.
%           However, I am not entirely sure that this is foolproof if the axis crossing lies on the rectangle itself so that the position of the crossing is also
%           generated by v_conicline the result might then depend on the ordering of these coincident points after sorting.
%       2.  The orientation of the lines is not necessarily consistent (not sure what the best choice is)
%       3.  The ordering of the foci is not necessarily consistent (not sure what the best choice is)
%

