        p.slat=Inf;                                     % semi-latus rectum
        p.eccy=1;                                       % eccentricity = conic-to-focus/conic-to-directrix
        p.focp=Inf;                                     % focus-to-directrix distance (focal parameter)
        if doax
            drad=1;                                                     % display radius
            ax=[p.cent(1)+figar*[-drad drad] p.cent(2)+[-drad drad]];    % axis limits
        end
        if doxy
            xyc=v_clipline(p.line,ax);                          % clip the conic line to the clipping rectangle
            if ~isnan(xyc(1))                                   % if line exists
                xy=reshape(xyc,2,2);                            % insert Nan points to separate the lines
            end
        end
    case 13 % 13: entire plane [0 0 0 0 0 0]
        p.nclp=[0 0 -1];                                        % number of curves, lines and points in the conic ([0 0 -1] for whole plane)
        p.cent=zeros(2,1);                                      % conic centre
        if doax
            drad=1;                                                     % display radius
            ax=[p.cent(1)+figar*[-drad drad] p.cent(2)+[-drad drad]];    % axis limits
        end
